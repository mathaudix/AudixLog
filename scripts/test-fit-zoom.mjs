import { build } from 'esbuild';
import { pathToFileURL } from 'node:url';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const dir = mkdtempSync(join(tmpdir(), 'fitzoom-'));
const out = join(dir, 'fitZoom.mjs');
await build({ entryPoints: ['src/features/labels/fitZoom.ts'], outfile: out, format: 'esm', bundle: true, platform: 'node' });
const { fitZoom, pxPerUnit, ZOOM_MIN, ZOOM_MAX } = await import(pathToFileURL(out).href);
const ok = (c, m) => { if (!c) { console.error('FAIL', m); process.exit(1); } };
const wide = fitZoom({ viewportWidth: 1000, viewportHeight: 800, labelWidth: 181, labelHeight: 113 });
ok(wide >= ZOOM_MIN && wide <= ZOOM_MAX, 'largo dentro dos limites');
const tall = fitZoom({ viewportWidth: 800, viewportHeight: 600, labelWidth: 378, labelHeight: 567 });
ok(tall * 567 / 100 <= 600 - 96 + 0.5, 'alto cabe na altura');
ok(tall * 378 / 100 <= 800 - 96 + 0.5, 'alto cabe na largura');
ok(fitZoom({ viewportWidth: 100, viewportHeight: 100, labelWidth: 378, labelHeight: 567 }) >= ZOOM_MIN, 'pequeno respeita minimo');
ok(fitZoom({ viewportWidth: 1, viewportHeight: 1, labelWidth: 0, labelHeight: 0 }) === 100, 'dimensao invalida = 100');
ok(pxPerUnit(378, 378) === 1 && pxPerUnit(0, 378) === 0, 'pxPerUnit');
console.log('test-fit-zoom OK');
