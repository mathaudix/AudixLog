import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';
import { transform } from 'esbuild';

const source = await readFile(new URL('../src/utils/accessKey.ts', import.meta.url), 'utf8');
const built = await transform(source, { loader: 'ts', format: 'cjs' });
const module = { exports: {} };
vm.runInNewContext(built.code, { module, exports: module.exports });
const { normalizeAccessKey, nfNumberFromKey, parseAccessKey } = module.exports;
const key = '12345678901234567890123450000012345678901234';
assert.equal(key.length, 44);
assert.equal(normalizeAccessKey(`https://exemplo.test/qrcode?p=${key}`), key);
assert.equal(normalizeAccessKey(key.match(/.{1,4}/g).join(' ')), key);
assert.equal(nfNumberFromKey(key), key.slice(25, 34).replace(/^0+/, ''));
assert.equal(normalizeAccessKey('abc123'), '123');
const nfe = '35260112345678000195550010001234561123456786';
const parsed = parseAccessKey(nfe);
assert.ok(parsed);
assert.equal(parsed.uf, 'SP');
assert.equal(parsed.emissionMonth, '01/2026');
assert.equal(parsed.cnpjEmitente, '12.345.678/0001-95');
assert.equal(parsed.modelo, '55 NF-e');
assert.equal(parsed.serie, '1');
assert.equal(parsed.numero, '123456');
assert.equal(parsed.dvValido, true);
assert.equal(parseAccessKey(nfe.slice(0, 43) + '0')?.dvValido, false);
assert.equal(parseAccessKey('123'), null);
console.log('access-key parser tests passed');
console.log('access-key tests passed');
